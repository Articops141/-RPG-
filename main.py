def use_item(игрок, номер_предмета):
    if 0 <= номер_предмета < len(игрок['инвентарь']):
        предмет = игрок['инвентарь'][номер_предмета]
        if "зелье здоровья" in предмет:
            восстановление = 30
            if "среднее" in предмет:
                восстановление = 60
            elif "большое" in предмет:
                восстановление = 100
            heal_amount = min(игрок['макс_здоровье'] - игрок['здоровье'], восстановление)
            игрок['здоровье'] += heal_amount
            print(f"Использовано {предмет}! Восстановлено {heal_amount} здоровья.")
            игрок['инвентарь'].pop(номер_предмета)
            return True
    return False
