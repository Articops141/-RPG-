def fight(игрок, враг):
    print(f"Начинается битва с {враг['имя']}!")
    while игрок['здоровье'] > 0 and враг['здоровье'] > 0:
        print(f"\n--- Ваш ход ---")
        status_enemy(враг)
        print(f"Ваше здоровье: {игрок['здоровье']}/{игрок['макс_здоровье']}")
        действие = action()
        if действие == "1":
            attack_user(игрок, враг)
        elif действие == "2":
            use_item(игрок)
        elif действие == "3":
            if slope():
                print("Вы успешно уклонились от атаки!")
                continue
        if враг['здоровье'] > 0:
            attack_enemy(игрок, враг)
    if игрок['здоровье'] > 0:
        win(игрок, враг)
        return True
    else:
        lose(игрок)
        return False
