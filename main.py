def lvl(игрок):
    игрок['уровень'] += 1
    игрок['опыт'] -= игрок['опыт_до_уровня']
    игрок['опыт_до_уровня'] = int(игрок['опыт_до_уровня'] * 1.5)
    игрок['очки_навыков'] += 3
    игрок['макс_здоровье'] += 20
    игрок['здоровье'] = игрок['макс_здоровье']
    print(f"Поздравляем! {игрок['имя']} достиг {игрок['уровень']} уровня!")
